const { strict: assert } = require("node:assert");
void (async () => {
const { parse, run, suggest, demoCsv } = await import("../web/console-lab/traffic/engine.js");

const table = demoCsv(), demo = parse(table);
assert.equal(demo.reportedDays, 14);
assert.equal(demo.rows, 28);
assert.equal(demo.sessions, 990);
assert.equal(demo.pageviews, 1842);
assert.equal(demo.pages[0].label, "/guides");
assert.equal(demo.pages[0].sessions, 740);
assert.match(run("trend", demo).desc[1], /^\S.+%/);
assert.deepEqual(run("anomalies", demo).rows[0], ["2026-10-12", "162", "Spike"]);
assert.equal(run("channels", demo).rows[0][0], "organic search");
assert.equal(run("pages", demo).rows[0][0], "/guides");
assert.equal(suggest("How did traffic change week over week?"), "trend");
assert.equal(suggest("Write an overview for leadership"), "summary");
assert.equal(suggest("Rank landing pages"), "pages");
assert.equal(suggest("What source drove referrals?"), "channels");
assert.equal(suggest("Were there any sudden dips?"), "anomalies");
assert.equal(suggest("Open a ticket and email the owner"), null);
assert.equal(suggest("analyze the traffic"), null);
assert.throws(() => parse(table + "\n2026-10-01,/guides,ORGANIC SEARCH,1,2"), /already appear/);
assert.throws(() => parse(table + "\n2026-02-30,/,Organic,3,4"), /valid date/);
assert.throws(() => parse(table + "\n2026-10-01,/?identity=abc,Organic,3,4"), /landing path/);
assert.throws(() => parse(table + "\n2026-10-01,/,=cmd,3,4"), /channel label/);
assert.throws(() => parse(table + "\n2026-10-01,/,Other,3.5,4"), /whole numbers/);
assert.throws(() => parse(table + "\n2026-10-02,\"/\",Other,3,\"4"), /not closed/);
const missing = parse(table.split("\n").filter(line => !line.startsWith("2026-10-03")).join("\n"));
assert.equal(missing.missingDays, 1);
assert.equal(missing.timeline[2].sessions, null);
assert.match(run("trend", missing).desc[0], /14 consecutive/);
const zero = parse(table.split("\n").map((line, i) => i && i <= 14 ? line.replace(/,\d+,\d+$/, ",0,0") : line).join("\n"));
assert.match(run("trend", zero).desc[1], /undefined/);
assert.equal(parse('\ufeffchannel,pageviews,sessions,page,date\r\nOrganic,5,3,"/a,b",2026-10-01').pages[0].label, "/a,b");
console.log("Local traffic import, aggregate calculations, task routing and data-quality guards passed");
})().catch(error => { console.error(error); process.exitCode = 1; });
